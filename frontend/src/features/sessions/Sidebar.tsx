import type { MouseEvent } from 'react'
import { MessageSquarePlus, Trash2 } from 'lucide-react'
import { useTranslation } from 'react-i18next'

import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
  AlertDialogTrigger,
} from '@/components/ui/alert-dialog'
import { Button } from '@/components/ui/button'
import {
  Sidebar as SidebarRoot,
  SidebarContent,
  SidebarGroup,
  SidebarGroupContent,
  SidebarHeader,
  SidebarMenu,
  SidebarMenuAction,
  SidebarMenuButton,
  SidebarMenuItem,
} from '@/components/ui/sidebar'

import type { SessionSummary } from '../../api/types'
import { sessionPath } from '../../lib/route'
import { stageLabel } from '../chat/labels'

type Props = {
  sessions: SessionSummary[]
  activeId: string | null
  onSelect: (sessionId: string) => void
  onCreate: () => void
  onDelete: (sessionId: string) => void
}

export function Sidebar({ sessions, activeId, onSelect, onCreate, onDelete }: Props) {
  const { t, i18n } = useTranslation()
  const dateLocale = i18n.resolvedLanguage === 'en' ? 'en-US' : 'es-PE'

  return (
    <SidebarRoot collapsible="offcanvas">
      <SidebarHeader className="p-3">
        <Button type="button" onClick={onCreate} className="h-10 w-full font-semibold">
          <MessageSquarePlus aria-hidden="true" />
          {t('sidebar.newConversation')}
        </Button>
      </SidebarHeader>

      <SidebarContent>
        <SidebarGroup>
          <SidebarGroupContent>
            <SidebarMenu>
              {sessions.length === 0 && (
                <p className="text-muted-foreground px-2 py-3 text-xs">
                  {t('sidebar.noConversations')}
                </p>
              )}

              {sessions.map((session) => {
                const isActive = session.session_id === activeId

                // A real <a href>, not a <button>: this way it can be opened in a
                // new tab with a middle click or Ctrl/Cmd+click, its link copied
                // with a right click, or the URL simply pasted into another tab.
                // The plain click is intercepted to navigate without reloading the page.
                function handleClick(event: MouseEvent<HTMLAnchorElement>) {
                  const usesModifier =
                    event.button !== 0 ||
                    event.metaKey ||
                    event.ctrlKey ||
                    event.shiftKey ||
                    event.altKey
                  if (usesModifier) return
                  event.preventDefault()
                  onSelect(session.session_id)
                }

                return (
                  <SidebarMenuItem key={session.session_id}>
                    <SidebarMenuButton asChild isActive={isActive} className="h-auto py-2 pr-8">
                      <a
                        href={sessionPath(session.session_id)}
                        onClick={handleClick}
                        aria-current={isActive ? 'true' : undefined}
                      >
                        <span className="flex min-w-0 flex-col">
                          {/* The title is generated by the lightweight model in the
                              background; until it arrives, the conversation still
                              needs to be distinguishable. */}
                          <span className="block truncate text-sm">
                            {session.titulo || t('sidebar.untitledConversation')}
                          </span>
                          <span className="text-muted-foreground block truncate text-[11px]">
                            {new Date(session.last_update_time).toLocaleString(dateLocale, {
                              day: '2-digit',
                              month: 'short',
                              hour: '2-digit',
                              minute: '2-digit',
                            })}
                            {' · '}
                            {stageLabel(t, session.stage)}
                          </span>
                        </span>
                      </a>
                    </SidebarMenuButton>

                    <AlertDialog>
                      <AlertDialogTrigger asChild>
                        <SidebarMenuAction
                          showOnHover
                          aria-label={t('sidebar.deleteConversation')}
                          title={t('sidebar.deleteConversation')}
                          className="text-muted-foreground hover:text-destructive !top-1/2 !-translate-y-1/2"
                        >
                          <Trash2 aria-hidden="true" />
                        </SidebarMenuAction>
                      </AlertDialogTrigger>
                      <AlertDialogContent>
                        <AlertDialogHeader>
                          <AlertDialogTitle>{t('sidebar.deleteDialogTitle')}</AlertDialogTitle>
                          <AlertDialogDescription>
                            {t('sidebar.deleteDialogDescription', {
                              title: session.titulo || t('sidebar.untitledConversation'),
                            })}
                          </AlertDialogDescription>
                        </AlertDialogHeader>
                        <AlertDialogFooter>
                          <AlertDialogCancel>{t('sidebar.cancel')}</AlertDialogCancel>
                          {/* variant, not className: AlertDialogAction forwards
                              className to Radix's internal element, not to the
                              Button that computes bg-primary, so a color class
                              there competes with it on specificity and sometimes
                              loses. The variant is what the Button itself controls. */}
                          <AlertDialogAction
                            variant="destructive"
                            onClick={() => onDelete(session.session_id)}
                          >
                            {t('sidebar.delete')}
                          </AlertDialogAction>
                        </AlertDialogFooter>
                      </AlertDialogContent>
                    </AlertDialog>
                  </SidebarMenuItem>
                )
              })}
            </SidebarMenu>
          </SidebarGroupContent>
        </SidebarGroup>
      </SidebarContent>
    </SidebarRoot>
  )
}
